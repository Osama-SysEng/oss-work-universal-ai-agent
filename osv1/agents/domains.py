"""The 30 agent domains.

Each domain is a body of work with its own tools, its own risk level, and
its own vocabulary. The vocabulary is what System One uses to route a
request, so it is written as the words people actually use for that work.

The 30 domains combined with the 10 specializations in
:mod:`osv1.agents.specializations` produce the 300 specialized agents in
:mod:`osv1.agents.registry`.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class Domain:
    """One field of work."""

    key: str
    title: str
    summary: str
    keywords: tuple[str, ...]
    tools: tuple[str, ...]
    risk: str = "low"
    deliverables: tuple[str, ...] = ()

    def as_dict(self) -> dict:
        return {
            "key": self.key,
            "title": self.title,
            "summary": self.summary,
            "keywords": list(self.keywords),
            "tools": list(self.tools),
            "risk": self.risk,
            "deliverables": list(self.deliverables),
        }


